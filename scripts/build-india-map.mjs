/**
 * Turns the Wikimedia India SVG into a lean React component.
 *
 * Source: "Bharat (India) Map with Full Kashmir By Devilal.svg" (Wikimedia
 * Commons, **public domain**). Chosen over the CC BY-SA alternatives so the
 * page carries no share-alike obligation, and over the "de-facto" variants
 * because it shows the full territory India claims — the depiction required of
 * anything published for an Indian audience.
 *
 * The original is a 54 KB Illustrator/Inkscape export carrying editor metadata,
 * per-path fills and RDF licence blocks. None of that survives: we keep only
 * the path geometry and let the component colour it with currentColor, so the
 * map inherits the band's palette instead of shipping its own.
 *
 * Run with: node scripts/build-india-map.mjs
 * (Requires scripts/.cache/india.svg — see the download line below.)
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = resolve(root, "scripts/.cache/india.svg");
const OUT = resolve(root, "src/components/landing/indiaPaths.ts");

const REMOTE =
  "https://upload.wikimedia.org/wikipedia/commons/8/8e/Bharat_%28India%29_Map_with_Full_Kashmir_By_Devilal.svg";

if (!existsSync(SRC)) {
  mkdirSync(dirname(SRC), { recursive: true });
  const res = await fetch(REMOTE, {
    headers: { "User-Agent": "AgentFarmer/1.0 (vanoopkumar261@gmail.com)" },
  });
  if (!res.ok) throw new Error(`Download failed: ${res.status}`);
  writeFileSync(SRC, await res.text(), "utf8");
  console.log("Downloaded source SVG.");
}

const svg = readFileSync(SRC, "utf8");

const viewBox = /viewBox\s*=\s*"([^"]+)"/.exec(svg)?.[1];
if (!viewBox) throw new Error("No viewBox on the source SVG.");

// Only the geometry. Anything shorter than ~40 characters is a stray artefact
// rather than a state boundary.
const paths = [...svg.matchAll(/\sd\s*=\s*"([^"]+)"/g)]
  .map((m) => m[1].replace(/\s+/g, " ").trim())
  .filter((d) => d.length > 40);

const body = `/**
 * India's outline, as state-boundary path data.
 *
 * Generated by scripts/build-india-map.mjs from a public-domain Wikimedia
 * Commons SVG ("Bharat (India) Map with Full Kashmir By Devilal"). Do not edit
 * by hand — re-run the script instead.
 *
 * Geometry only: no fills, no stroke widths, no editor metadata. The component
 * that renders these supplies all styling, so the map takes the colour of
 * whatever band it sits in.
 */
export const INDIA_VIEWBOX = "${viewBox}";

export const INDIA_PATHS: readonly string[] = [
${paths.map((d) => `  ${JSON.stringify(d)},`).join("\n")}
];
`;

writeFileSync(OUT, body, "utf8");
console.log(`Wrote ${OUT}`);
console.log(`  viewBox: ${viewBox}`);
console.log(`  paths:   ${paths.length}`);
console.log(`  size:    ${(body.length / 1024).toFixed(1)} KB`);
